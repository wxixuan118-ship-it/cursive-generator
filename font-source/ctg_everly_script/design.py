def _arch(bx, pitch=168, top=XH):
    """One shoulder of n/m: bottom turn at bx, over the top, down to bx+pitch."""
    return [
        (bx, 14),
        (bx + 34, 170),
        (bx + 76, top - 24),
        (bx + 108, top),
        (bx + 138, top - 52),
        (bx + 148, 158),
        (bx + 152, 50),
        (bx + pitch, 14),
    ]


# The opening descent of n/m/u: entry lands on the peak, pen falls to baseline.

# Standard join strokes.  The shared tangent (46, 85) at the seam makes the
# previous exit and the next entry read as one continuous pen movement.
def _entry(*rest):
    return [(0, CONN), (46, 190)] + list(rest)


def _exit(start, adv, *mid):
    return [start] + list(mid) + [(adv - 46, 22), (adv, CONN)]


def _exit_high(start, adv, *mid):
    """Leaving from x-height: the pen coasts down into the join."""
    return [start] + list(mid) + [(adv - 40, 250), (adv, CONN)]



# ------------------------------------------------- digits, marks and symbols --
#
# These never join, so they are plain stroke collections: a list of
# (points, weight, closed) plus any solid dots.

OTHER = {}


def O(name, code, adv, strokes=(), dots=()):
    OTHER[name] = {
        "code": code, "adv": adv,
        "strokes": [(list(stroke[0]), stroke[1],
                     bool(stroke[2]) if len(stroke) > 2 else False)
                    for stroke in strokes],
        "dots": list(dots),
    }


def _ring(cx, cy, rx, ry, w=1.0):
    return (A(cx, cy, rx, ry, 0, 360, 25), w, True)



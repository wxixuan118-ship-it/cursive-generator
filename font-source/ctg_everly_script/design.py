"""Glyph designs for CTG Everly Script.

Every letter is a set of pen skeletons drawn upright in a 1000 unit em; the
slant is sheared into the skeleton at build time so stroke weight stays
perpendicular to the pen path instead of being distorted by an outline shear.

Lowercase letters are authored in three detachable pieces:

    entry   the join stroke that arrives from the previous letter,
            always starting at (0, CONN) with a fixed tangent
    body    the letter itself
    exit    the join stroke that leaves for the next letter,
            always ending at (adv, CONN) with the same tangent

Because entry and exit are separate strokes, the build can assemble four
contextual forms per letter (medial, initial, final, isolated) without
redrawing anything.
"""

